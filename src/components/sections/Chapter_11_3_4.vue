      <h4>Level 1: Phenomenological</h4>
      <ul>
        <li><strong>View:</strong> Photon is particle; light is electromagnetic wave</li>
        <li><strong>Domain:</strong> Classical electrodynamics, optics</li>
        <li><strong>Validity:</strong> Macroscopic phenomena, low energies</li>
      </ul>

      <h4>Level 2: Quantum Field Theory</h4>
      <ul>
        <li><strong>View:</strong> Photon is quantum of electromagnetic field; gauge boson of U(1) symmetry</li>
        <li><strong>Domain:</strong> QED, Standard Model</li>
        <li><strong>Validity:</strong> All experimentally accessible energies (up to TeV scale)</li>
      </ul>

      <h4>Level 3: Emergent Gauge Theory</h4>
      <ul>
        <li><strong>View:</strong> Photon is collective excitation of underlying quantum matter; gauge symmetry is emergent</li>
        <li><strong>Domain:</strong> Speculative fundamental theory; condensed matter realizations</li>
