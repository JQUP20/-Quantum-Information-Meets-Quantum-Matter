    <h1>11.1.2 Electromagnetic Revolution</h1>

    <p>
      The electromagnetic revolution of the 19th century fundamentally expanded physics beyond Newton's mechanical framework. Through the work of Faraday, Maxwell, and others, electricity and magnetism were unified into a single electromagnetic field theory, revealing light as an electromagnetic wave and introducing the revolutionary concept of the <em>field</em> as a fundamental physical entity. This revolution transformed our understanding of forces, causality, and the structure of space itself.
    </p>

    <h2>From Isolated Phenomena to Unified Theory</h2>

    <h3>Early Electrical and Magnetic Discoveries</h3>

    <div class="info-box">
      <h3>Pre-Unification Landscape (1600-1820)</h3>
      <ul>
        <li><strong>William Gilbert (1600):</strong> <em>De Magnete</em>—systematic study of magnetism, Earth as giant magnet</li>
        <li><strong>Charles Coulomb (1785):</strong> Inverse square law for electrostatic force: F = k q₁q₂/r²</li>
        <li><strong>Alessandro Volta (1800):</strong> Voltaic pile—first continuous electric current</li>
        <li><strong>Hans Christian Ørsted (1820):</strong> Electric current deflects magnetic compass—first connection between electricity and magnetism</li>
      </ul>
      <p>
        Before 1820, electricity and magnetism were studied as separate phenomena. Ørsted's discovery that electric currents produce magnetic fields revealed a deep connection, catalyzing intensive research.
      </p>
    </div>

    <h3>Ampère and Faraday: Founding Electromagnetism</h3>

    <div class="highlight-box">
      <h4>André-Marie Ampère (1775-1836)</h4>
      <p>
        Immediately after Ørsted's discovery, Ampère developed the mathematical theory of electromagnetism:
      </p>
      <ul>
        <li><strong>Ampère's law:</strong> Relates magnetic field to electric current: ∮ <strong>B</strong> · d<strong>l</strong> = μ₀I</li>
        <li><strong>Force between currents:</strong> Parallel currents attract, antiparallel repel</li>
        <li><strong>Mathematical formulation:</strong> First rigorous mathematical description of electromagnetic forces</li>
      </ul>

      <h4>Michael Faraday (1791-1867)</h4>
      <p>
        Faraday revolutionized electromagnetic theory through experimental genius and conceptual innovation:
      </p>
      <ul>
        <li><strong>Electromagnetic induction (1831):</strong> Changing magnetic field produces electric field: ∇ × <strong>E</strong> = -∂<strong>B</strong>/∂t</li>
        <li><strong>Field concept:</strong> Introduced "lines of force" filling space—revolutionary alternative to action at a distance</li>
        <li><strong>Field energy:</strong> Recognized that energy resides in the field itself, not just in charges and currents</li>
        <li><strong>Unification vision:</strong> Believed all forces (gravity, electricity, magnetism, light) would ultimately unify</li>
      </ul>
