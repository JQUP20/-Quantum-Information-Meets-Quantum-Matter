    <h2>Maxwell's Synthesis: The Electromagnetic Field</h2>

    <p>
      James Clerk Maxwell (1831-1879) transformed Faraday's intuitive field concept into rigorous mathematical theory, achieving the first great unification in physics and predicting that light is an electromagnetic wave.
    </p>

    <h3>Maxwell's Equations</h3>

    <div class="info-box">
      <h3>The Four Equations That Changed Physics</h3>

      <p><strong>In differential form (SI units):</strong></p>

      <div class="equation-group">
        <div class="equation">
          ∇ · <strong>E</strong> = ρ/ε₀ <span class="label">(Gauss's law)</span>
        </div>
        <p class="explanation">Electric charges create electric fields; field lines emanate from positive charges and terminate on negative charges.</p>

        <div class="equation">
          ∇ · <strong>B</strong> = 0 <span class="label">(No magnetic monopoles)</span>
        </div>
        <p class="explanation">Magnetic field lines form closed loops; isolated magnetic charges (monopoles) do not exist.</p>

        <div class="equation">
          ∇ × <strong>E</strong> = -∂<strong>B</strong>/∂t <span class="label">(Faraday's law)</span>
        </div>
        <p class="explanation">Changing magnetic fields induce circulating electric fields; basis of generators and transformers.</p>

        <div class="equation">
          ∇ × <strong>B</strong> = μ₀<strong>J</strong> + μ₀ε₀ ∂<strong>E</strong>/∂t <span class="label">(Ampère-Maxwell law)</span>
        </div>
        <p class="explanation">Electric currents and changing electric fields produce magnetic fields. The displacement current term (μ₀ε₀ ∂<strong>E</strong>/∂t) was Maxwell's revolutionary addition.</p>
      </div>
    </div>

    <h3>Maxwell's Revolutionary Contribution: Displacement Current</h3>

    <div class="highlight-box">
      <h4>The Missing Term That Unified Light and Electromagnetism</h4>
      <p>
        Maxwell recognized an inconsistency in Ampère's law. When applied to a charging capacitor:
      </p>
      <ul>
        <li><strong>Problem:</strong> Current flows in wires but not between capacitor plates, yet magnetic field circulates around entire circuit</li>
        <li><strong>Solution:</strong> Changing electric field between plates acts like a current—the "displacement current"</li>
        <li><strong>Mathematical:</strong> Added ε₀ ∂<strong>E</strong>/∂t term to Ampère's law to ensure ∇ · (∇ × <strong>B</strong>) = 0</li>
      </ul>

      <p><strong>Profound consequences:</strong></p>
      <ol>
        <li><strong>Symmetry:</strong> Changing <strong>E</strong> produces <strong>B</strong>, just as changing <strong>B</strong> produces <strong>E</strong></li>
        <li><strong>Electromagnetic waves:</strong> Fields can sustain each other in propagating waves</li>
        <li><strong>Speed of light:</strong> Wave speed v = 1/√(μ₀ε₀) = 3 × 10⁸ m/s—exactly the measured speed of light!</li>
        <li><strong>Light is electromagnetic:</strong> Light is not a separate phenomenon but an electromagnetic wave</li>
      </ol>
    </div>

    <h3>Electromagnetic Waves and the Nature of Light</h3>

    <div class="info-box">
      <h3>Wave Equation and Light</h3>
      <p>
        From Maxwell's equations in vacuum (ρ = 0, <strong>J</strong> = 0), one derives:
      </p>
      <div class="equation">
        ∇²<strong>E</strong> - (1/c²) ∂²<strong>E</strong>/∂t² = 0
        <br>
        ∇²<strong>B</strong> - (1/c²) ∂²<strong>B</strong>/∂t² = 0
      </div>
      <p>
        where c = 1/√(μ₀ε₀). These are wave equations with propagation speed c.
      </p>

      <h4>Properties of Electromagnetic Waves</h4>
      <ul>
        <li><strong>Transverse:</strong> <strong>E</strong> and <strong>B</strong> perpendicular to propagation direction <strong>k</strong></li>
        <li><strong>Perpendicular fields:</strong> <strong>E</strong> ⊥ <strong>B</strong>, with <strong>E</strong> × <strong>B</strong> ∥ <strong>k</strong></li>
        <li><strong>Equal magnitudes:</strong> |<strong>E</strong>| = c|<strong>B</strong>|</li>
        <li><strong>Spectrum:</strong> All frequencies possible—radio, microwave, infrared, visible, UV, X-ray, gamma ray</li>
        <li><strong>Energy transport:</strong> Poynting vector <strong>S</strong> = (<strong>E</strong> × <strong>B</strong>)/μ₀ gives energy flux</li>
      </ul>
