    <h2>Unfinished Business: Seeds of Future Revolutions</h2>

    <p>
      Despite its triumphs, electromagnetic theory raised new puzzles that would drive the next revolutions:
    </p>

    <ul>
      <li><strong>Ether problem:</strong> If light is a wave, what medium vibrates? Michelson-Morley experiment (1887) found no evidence for ether</li>
      <li><strong>Invariance puzzle:</strong> Why are Maxwell's equations the same in all inertial frames? What happened to Galilean relativity?</li>
      <li><strong>Blackbody radiation:</strong> Classical electromagnetism predicts ultraviolet catastrophe—infinite energy radiation</li>
      <li><strong>Photoelectric effect:</strong> Light ejects electrons instantly, inconsistent with wave picture</li>
      <li><strong>Atomic stability:</strong> Accelerating charges in atomic orbits should radiate away all energy instantaneously</li>
    </ul>

    <p>
      These problems would lead to special relativity (solving the ether and invariance puzzles) and quantum mechanics (solving blackbody, photoelectric, and atomic stability problems). Yet Maxwell's electromagnetic field theory, born in the 19th century, would survive intact into the 21st century—reformulated but unrefuted, a lasting monument to the power of field-based physics.
    </p>

