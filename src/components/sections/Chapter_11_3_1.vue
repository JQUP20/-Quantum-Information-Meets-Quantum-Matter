        <li><strong>Photon (γ):</strong> Electromagnetic force</li>
        <li><strong>W⁺, W⁻, Z⁰:</strong> Weak nuclear force</li>
        <li><strong>8 gluons (g):</strong> Strong nuclear force</li>
        <li><strong>Higgs boson (H):</strong> Mass generation</li>
      </ul>

      <h5>Governing Principles</h5>
      <ul>
        <li><strong>Quantum field theory:</strong> Particles are excitations of quantum fields</li>
        <li><strong>Gauge symmetry:</strong> Forces arise from local symmetries: SU(3) × SU(2) × U(1)</li>
        <li><strong>Spontaneous symmetry breaking:</strong> Higgs mechanism gives particles mass</li>
        <li><strong>Renormalizability:</strong> Well-defined predictions at all energy scales</li>
      </ul>

      <p><strong>Empirical success:</strong> Tested to extraordinary precision (e.g., electron g-factor accurate to 10⁻¹² ).</p>
