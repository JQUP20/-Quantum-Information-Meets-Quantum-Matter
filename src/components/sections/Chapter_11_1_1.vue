    <h1>11.1.1 Mechanical Revolution</h1>

    <p>
      The mechanical revolution, spanning from Galileo's experimental insights in the early 17th century to Newton's synthesis in the <em>Principia Mathematica</em> (1687), fundamentally transformed humanity's understanding of motion, force, and the nature of physical law. This revolution established the first mathematical framework for describing natural phenomena and laid the philosophical and methodological foundation for all subsequent physics.
    </p>

    <h2>Historical Context and Intellectual Landscape</h2>

    <div class="info-box">
      <h3>Pre-Newtonian Natural Philosophy</h3>
      <p>
        Before the mechanical revolution, natural philosophy was dominated by Aristotelian concepts:
      </p>
      <ul>
        <li><strong>Natural motion:</strong> Objects had inherent tendencies to move toward their "natural places" (earth downward, fire upward)</li>
        <li><strong>Violent motion:</strong> Required continuous application of force; motion ceased when force was removed</li>
        <li><strong>Teleological explanation:</strong> Objects moved "to achieve their purpose" rather than following mathematical laws</li>
        <li><strong>Qualitative description:</strong> Natural philosophy emphasized classification and purpose over quantitative measurement</li>
        <li><strong>Celestial-terrestrial divide:</strong> Heavenly bodies obeyed different, perfect laws than earthly objects</li>
      </ul>
    </div>

    <h3>Galileo's Revolutionary Insights (1564-1642)</h3>

    <div class="highlight-box">
      <h4>Galileo's Methodological Innovations</h4>
      <ol>
        <li><strong>Mathematical idealization:</strong> Focus on idealized cases (frictionless motion, point masses) that reveal fundamental principles</li>
        <li><strong>Experimental method:</strong> Systematic observation under controlled conditions (inclined planes, pendulums)</li>
        <li><strong>Quantitative measurement:</strong> Precise measurement of time, distance, and velocity</li>
        <li><strong>Inertial principle:</strong> Bodies maintain uniform motion unless acted upon by external forces</li>
        <li><strong>Relativity of motion:</strong> Observers in uniform motion cannot detect their motion by mechanical experiments</li>
      </ol>
    </div>

