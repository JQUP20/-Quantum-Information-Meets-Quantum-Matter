    <h2>Newton's Synthesis and the <em>Principia</em></h2>

    <p>
      Isaac Newton (1643-1727) synthesized Galileo's terrestrial mechanics, Kepler's planetary laws, and his own innovations into a unified mathematical framework that described both earthly and celestial motion. The <em>Philosophiæ Naturalis Principia Mathematica</em> (1687) remains one of the most influential scientific works ever written.
    </p>

    <h3>Newton's Three Laws of Motion</h3>

    <div class="info-box">
      <h3>The Foundation of Classical Mechanics</h3>

      <h4>First Law (Law of Inertia)</h4>
      <p class="equation-display">
        Every body continues in its state of rest or uniform motion in a straight line unless compelled to change that state by forces impressed upon it.
      </p>
      <p>
        <strong>Revolutionary insight:</strong> No force is required to maintain uniform motion—only to change it. This contradicted Aristotelian physics and established inertial reference frames as fundamental.
      </p>

      <h4>Second Law (F = ma)</h4>
      <p class="equation-display">
        The change of motion is proportional to the motive force impressed and takes place along the straight line in which that force is impressed.
      </p>
      <div class="equation">
        <strong>F</strong> = m<strong>a</strong> = m d²<strong>r</strong>/dt²
      </div>
      <p>
        <strong>Revolutionary insight:</strong> Force causes acceleration, not velocity. This differential equation relates instantaneous force to instantaneous acceleration, enabling prediction of future motion from present conditions.
      </p>

      <h4>Third Law (Action-Reaction)</h4>
      <p class="equation-display">
        To every action there is always opposed an equal reaction; or, the mutual actions of two bodies upon each other are always equal and directed to contrary parts.
      </p>
      <p>
        <strong>Revolutionary insight:</strong> Forces always occur in pairs; isolated forces do not exist. This implies momentum conservation and extends mechanics to systems of interacting bodies.
      </p>
    </div>

    <h3>Universal Gravitation</h3>

    <div class="highlight-box">
      <h4>The First Universal Law of Physics</h4>
      <div class="equation">
        F = G (m₁m₂)/r²
      </div>
      <p>
        Newton's law of universal gravitation unified terrestrial and celestial mechanics:
      </p>
      <ul>
        <li><strong>Same law everywhere:</strong> Applies to falling apples, lunar orbit, planetary motion, and galactic dynamics</li>
        <li><strong>Action at a distance:</strong> Gravitational force acts instantaneously across space (troubling to Newton himself)</li>
        <li><strong>Inverse square law:</strong> Force diminishes with distance squared, following from geometry of space</li>
        <li><strong>Predictive power:</strong> Explains Kepler's laws, tides, Earth's shape, precession of equinoxes</li>
      </ul>

      <h5>Mathematical Triumph: Deriving Kepler's Laws</h5>
      <p>
        From F = ma and F = GMm/r², Newton derived Kepler's three empirical laws:
      </p>
      <ol>
        <li><strong>Elliptical orbits:</strong> Planets move in ellipses with Sun at one focus (follows from 1/r² force)</li>
        <li><strong>Equal areas:</strong> Radius vector sweeps equal areas in equal times (angular momentum conservation)</li>
        <li><strong>Period-distance relation:</strong> T² ∝ a³ (consequence of specific 1/r² dependence)</li>
      </ol>
      <p>
        This derivation demonstrated that empirical regularities arise from deeper mathematical principles—a model for all subsequent theoretical physics.
      </p>
    </div>

