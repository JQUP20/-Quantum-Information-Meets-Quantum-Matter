    <h1>11.1.3 Relativity Revolution</h1>

    <p>
      The relativity revolution, culminating in Einstein's special (1905) and general (1915) theories of relativity, overthrew Newton's concepts of absolute space and time while revealing the deep unity of space, time, matter, and energy. This revolution showed that the arena of physics—spacetime itself—is dynamical, observer-dependent, and intimately connected to the matter and energy it contains. Relativity transformed our understanding of causality, geometry, and the very fabric of reality.
    </p>

    <h2>Crisis in Late 19th Century Physics</h2>

    <h3>The Ether Hypothesis and Its Contradictions</h3>

    <div class="info-box">
      <h3>The Luminiferous Ether</h3>
      <p>
        Maxwell's electromagnetic waves required a medium—by analogy with sound waves in air or water waves in water. The hypothetical "luminiferous ether" was proposed with paradoxical properties:
      </p>
      <ul>
        <li><strong>Required properties:</strong>
          <ul>
            <li>Permeates all space, even vacuum</li>
            <li>Extremely rigid to support light's high speed (c = 3 × 10⁸ m/s)</li>
            <li>Zero density to allow planetary motion without friction</li>
            <li>Transparent to all electromagnetic radiation</li>
            <li>Provides absolute rest frame for Maxwell's equations</li>
          </ul>
        </li>
        <li><strong>Contradictions:</strong> No material could be both extremely rigid (to support transverse waves at enormous speed) and have zero resistance to motion</li>
      </ul>
    </div>

    <h3>Michelson-Morley Experiment (1887)</h3>

    <div class="highlight-box">
      <h4>The Most Famous "Failed" Experiment in Physics</h4>
      <p>
        Albert Michelson and Edward Morley designed an interferometer to detect Earth's motion through the ether:
      </p>
      <ul>
        <li><strong>Expectation:</strong> Light traveling parallel to Earth's motion through ether should have different speed than light traveling perpendicular</li>
        <li><strong>Prediction:</strong> Interference fringes should shift as apparatus rotates</li>
        <li><strong>Result:</strong> No fringe shift detected—null result to high precision</li>
        <li><strong>Implication:</strong> Either ether doesn't exist, or Earth somehow drags it along (also ruled out by stellar aberration)</li>
      </ul>

      <p><strong>Attempted explanations:</strong></p>
      <ol>
        <li><strong>Lorentz-FitzGerald contraction:</strong> Objects contract in direction of motion through ether by exact amount to cancel expected effect—ad hoc</li>
        <li><strong>Ballistic theory:</strong> Light speed depends on source (like bullets from moving gun)—contradicted by observations</li>
        <li><strong>Einstein's radical solution:</strong> Abandon ether entirely; light speed is constant in all inertial frames</li>
      </ol>
    </div>

    <h2>Special Relativity (1905)</h2>

    <h3>Einstein's Two Postulates</h3>

    <div class="info-box">
      <h3>Foundation of Special Relativity</h3>

      <h4>Postulate 1: Principle of Relativity</h4>
      <p>
        The laws of physics are the same in all inertial reference frames.
      </p>
      <p class="explanation">
        No mechanical or electromagnetic experiment can determine absolute velocity. This extends Galilean relativity from mechanics to all physics.
      </p>

      <h4>Postulate 2: Invariance of Light Speed</h4>
      <p>
        The speed of light in vacuum is the same for all observers, independent of the motion of the light source or observer.
      </p>
      <p class="explanation">
        c = 299,792,458 m/s in every inertial frame. This contradicts Galilean velocity addition but is required by Maxwell's equations.
      </p>

      <p><strong>Revolutionary consequence:</strong> Space and time cannot be absolute. Observers in relative motion must disagree about simultaneity, durations, and distances.</p>
    </div>

    <h3>Relativity of Simultaneity and Lorentz Transformations</h3>

    <div class="highlight-box">
      <h4>Breakdown of Absolute Time</h4>
      <p>
        Events simultaneous in one frame are not simultaneous in another frame moving relative to it:
      </p>
      <ul>
        <li><strong>Einstein's train thought experiment:</strong> Lightning strikes both ends of moving train simultaneously in track frame, but not in train frame</li>
        <li><strong>Implication:</strong> "Now" depends on observer—no universal present moment</li>
        <li><strong>Causality preserved:</strong> Causal order (timelike separated events) is invariant; only spacelike separated events can have frame-dependent order</li>
      </ul>

      <h4>Lorentz Transformations</h4>
      <p>
        Coordinates in frame S' moving with velocity v relative to frame S:
      </p>
      <div class="equation">
        t' = γ(t - vx/c²)
        <br>
        x' = γ(x - vt)
        <br>
        y' = y
        <br>
        z' = z
        <br><br>
        where γ = 1/√(1 - v²/c²)
      </div>
      <p>
        Note: Space and time mix—time transformation depends on position, position transformation depends on time. Space and time are unified into spacetime.
      </p>
    </div>

