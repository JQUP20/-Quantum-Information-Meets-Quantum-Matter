    <h3>Spacetime and Minkowski Geometry</h3>

    <div class="info-box">
      <h3>Minkowski's Geometric Interpretation (1908)</h3>
      <p>
        Hermann Minkowski reformulated special relativity geometrically:
      </p>
      <ul>
        <li><strong>Spacetime:</strong> 4-dimensional manifold with coordinates (ct, x, y, z)</li>
        <li><strong>Events:</strong> Points in spacetime</li>
        <li><strong>Worldlines:</strong> Trajectories of particles through spacetime</li>
        <li><strong>Invariant interval:</strong>
          <div class="equation">
            ds² = -c²dt² + dx² + dy² + dz²
          </div>
          All observers agree on ds² (spacetime analog of distance)
        </li>
        <li><strong>Light cones:</strong> Structure spacetime into timelike (ds² < 0), lightlike (ds² = 0), and spacelike (ds² > 0) separated events</li>
      </ul>

      <p><strong>Minkowski's famous declaration (1908):</strong></p>
      <blockquote>
        "Henceforth space by itself, and time by itself, are doomed to fade away into mere shadows, and only a kind of union of the two will preserve an independent reality."
      </blockquote>
    </div>

    <h2>General Relativity (1915)</h2>

    <h3>From Special to General: The Equivalence Principle</h3>

    <div class="highlight-box">
      <h4>Einstein's "Happiest Thought" (1907)</h4>
      <p>
        The equivalence principle: Physics in a uniform gravitational field is indistinguishable from physics in an accelerating reference frame.
      </p>
      <ul>
        <li><strong>Weak equivalence:</strong> Gravitational mass equals inertial mass (all objects fall at same rate)</li>
        <li><strong>Einstein equivalence:</strong> No local experiment can distinguish gravity from acceleration</li>
        <li><strong>Implication:</strong> Gravity is not a force but a manifestation of spacetime curvature</li>
      </ul>

      <p><strong>Thought experiments:</strong></p>
      <ol>
        <li><strong>Elevator in space:</strong> Acceleration upward feels identical to gravitational field pointing down</li>
        <li><strong>Free-falling observer:</strong> Experiences weightlessness—locally cancels gravity (inertial frame)</li>
        <li><strong>Light bending:</strong> Light beam curves downward in accelerating rocket, so must curve in gravitational field</li>
      </ol>
    </div>

    <h3>Curved Spacetime and the Einstein Field Equations</h3>

    <div class="info-box">
      <h3>Gravity as Geometry</h3>
      <p>
        General relativity describes gravity as the curvature of spacetime caused by mass-energy:
      </p>

      <h4>Einstein Field Equations</h4>
      <div class="equation">
        G<sub>μν</sub> + Λg<sub>μν</sub> = (8πG/c⁴) T<sub>μν</sub>
      </div>
      <p>
        where:
      </p>
      <ul>
        <li><strong>G<sub>μν</sub>:</strong> Einstein tensor (encodes spacetime curvature)</li>
        <li><strong>g<sub>μν</sub>:</strong> Metric tensor (defines spacetime geometry)</li>
        <li><strong>T<sub>μν</sub>:</strong> Stress-energy tensor (describes matter/energy distribution)</li>
        <li><strong>Λ:</strong> Cosmological constant (vacuum energy density)</li>
      </ul>

      <p><strong>John Wheeler's summary:</strong></p>
      <blockquote>
        "Spacetime tells matter how to move; matter tells spacetime how to curve."
      </blockquote>
    </div>

    <h3>Key Features of General Relativity</h3>

    <div class="comparison-box">
      <h3>Revolutionary Aspects</h3>
      <ul>
        <li><strong>No gravitational force:</strong> Objects follow geodesics (straightest paths) in curved spacetime</li>
        <li><strong>Dynamic spacetime:</strong> Geometry is not fixed background but responds to matter-energy</li>
        <li><strong>Frame-dragging:</strong> Rotating masses drag spacetime around them (Lense-Thirring effect)</li>
        <li><strong>Gravitational time dilation:</strong> Clocks run slower in stronger gravitational fields</li>
        <li><strong>Gravitational waves:</strong> Ripples in spacetime geometry propagating at speed c</li>
        <li><strong>Black holes:</strong> Regions where spacetime curvature becomes so extreme that escape is impossible</li>
        <li><strong>Expanding universe:</strong> Spacetime itself expands, carrying galaxies apart</li>
      </ul>
    </div>

