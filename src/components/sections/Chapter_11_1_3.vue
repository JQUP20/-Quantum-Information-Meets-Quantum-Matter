    <h2>Relativity and Quantum Mechanics: Unfinished Business</h2>

    <div class="highlight-box">
      <h4>The Incompatibility Problem</h4>
      <p>
        General relativity and quantum mechanics are both experimentally confirmed to extraordinary precision, yet they are fundamentally incompatible:
      </p>
      <ul>
        <li><strong>GR:</strong> Spacetime is smooth, deterministic, classical geometric structure</li>
        <li><strong>QM:</strong> Inherently probabilistic, superposition of states, observer-dependent reality</li>
        <li><strong>Conflict:</strong> What is quantum state of spacetime itself? How does geometry behave in superposition?</li>
        <li><strong>Quantum gravity problem:</strong> No successful theory quantizing general relativity exists</li>
        <li><strong>Regimes:</strong>
          <ul>
            <li>QM works: atomic scales, low energies, weak gravity</li>
            <li>GR works: large scales, strong gravity, classical limits</li>
            <li>Both needed: Black hole singularities, Big Bang, Planck scale (10⁻³⁵ m, 10⁻⁴³ s)</li>
          </ul>
        </li>
      </ul>

      <p><strong>Approaches to quantum gravity:</strong></p>
      <ul>
        <li>String theory: Fundamental strings in 10/11 dimensions</li>
        <li>Loop quantum gravity: Quantize spacetime itself into discrete units</li>
        <li>Emergent gravity: Spacetime emerges from quantum entanglement (connection to this book's themes!)</li>
      </ul>
